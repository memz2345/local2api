// 开源许可相关：pubspec.lock 版本解析、许可标识识别，
// 以及 miuix / Material 两套页面的渲染回归（不依赖真实 NOTICES）。

import 'package:flutter/material.dart';
import 'package:flutter_miuix/miuix.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:local2api/l10n/app_localizations.dart';
import 'package:local2api/services/oss_license_service.dart';
import 'package:local2api/ui/app_theme.dart';
import 'package:local2api/ui/miuix/miuix_about_page.dart' show kAppName;
import 'package:local2api/ui/miuix/miuix_open_source_licenses_page.dart';
import 'package:local2api/ui/miuix/miuix_oss_package_license_page.dart';
import 'package:local2api/ui/open_source_licenses_page.dart';
import 'package:shared_preferences/shared_preferences.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  setUp(() {
    SharedPreferences.setMockInitialValues({});
    debugResetOssLicenseCache();
  });

  test('parseLockVersions：只认 packages: 下两格缩进的包名与 version', () {
    const raw = '''
# Generated by pub
packages:
  path:
    dependency: "direct main"
    description:
      name: path
      url: "https://pub.dev"
    source: hosted
    version: "1.9.0"
  flutter_miuix:
    dependency: "direct main"
    description:
      name: flutter_miuix
      url: "https://pub.dev"
    source: hosted
    version: "1.3.0"
sdks:
  dart: ">=3.12.0 <4.0.0"
''';
    final versions = parseLockVersions(raw);
    expect(versions['path'], '1.9.0');
    expect(versions['flutter_miuix'], '1.3.0');
    // sdks 段不是包
    expect(versions.containsKey('dart'), isFalse);
  });

  test('detectLicenseId：常见许可能认出来，陌生正文归 Other', () {
    expect(
      detectLicenseId('MIT License\n\nPermission is hereby granted, free of charge'),
      'MIT',
    );
    expect(
      detectLicenseId('Apache License\nVersion 2.0, January 2004'),
      'Apache-2.0',
    );
    expect(
      detectLicenseId('Redistribution and use in source and binary forms, '
          'with or without modification, are permitted'),
      anyOf('BSD-2-Clause', 'BSD-3-Clause'),
    );
    expect(detectLicenseId('Proprietary blobs, all rights reserved'), 'Other');
  });

  test('OssPackage.fullText：多份许可用分隔线串起来', () {
    const pkg = OssPackage(
      name: 'demo',
      licenses: [
        [OssParagraph('LICENSE A', 0)],
        [OssParagraph('LICENSE B', 0)],
      ],
      licenseIds: ['MIT', 'Apache-2.0'],
      version: '1.0.0',
    );
    expect(pkg.licenseCount, 2);
    expect(pkg.fullText, contains('LICENSE A'));
    expect(pkg.fullText, contains('LICENSE B'));
    expect(pkg.distinctLicenseIds, ['MIT', 'Apache-2.0']);
  });

  Future<void> pumpPage(WidgetTester tester, Widget page) async {
    tester.view.physicalSize = const Size(1200, 2400);
    tester.view.devicePixelRatio = 2.0;
    addTearDown(tester.view.reset);
    await tester.pumpWidget(
      MiuixThemeController(
        colorSchemeMode: MiuixColorSchemeMode.monetLight,
        keyColor: const Color(0xFF3482FF),
        child: MaterialApp(
          locale: const Locale('zh', 'CN'),
          localizationsDelegates: AppLocalizations.localizationsDelegates,
          supportedLocales: AppLocalizations.supportedLocales,
          theme: AppTheme.light(),
          home: page,
        ),
      ),
    );
    await tester.pumpAndSettle();
  }

  testWidgets('miuix 许可页：标题 / 搜索框 / 应用名都在', (tester) async {
    late AppLocalizations l10n;
    await pumpPage(
      tester,
      Builder(
        builder: (context) {
          l10n = AppLocalizations.of(context);
          return const MiuixOpenSourceLicensesPage();
        },
      ),
    );
    expect(find.text(l10n.ossTitle), findsWidgets);
    expect(find.text(kAppName), findsOneWidget);
    // MiuixTextField 内部仍是 TextField，搜索框只有一个。
    expect(find.byType(TextField), findsOneWidget);
  });

  testWidgets('Material 许可页：同一份标题与搜索入口', (tester) async {
    late AppLocalizations l10n;
    await pumpPage(
      tester,
      Builder(
        builder: (context) {
          l10n = AppLocalizations.of(context);
          return const OpenSourceLicensesPage();
        },
      ),
    );
    expect(find.text(l10n.ossTitle), findsWidgets);
    expect(find.byIcon(Icons.search_rounded), findsWidgets);
    expect(find.byType(TextField), findsOneWidget);
  });

  testWidgets('miuix 包许可页：段落按缩进渲染、复制按钮在', (tester) async {
    const pkg = OssPackage(
      name: 'demo-package',
      licenses: [
        [
          OssParagraph('MIT License', 0),
          // NOTICES 的段落文本不带缩进，缩进在 indent 里（渲染时 ×16）。
          OssParagraph('Permission is hereby granted', 1),
        ],
      ],
      licenseIds: ['MIT'],
      version: '2.1.0',
    );
    await pumpPage(tester, const MiuixOssPackageLicensePage(package: pkg));
    expect(find.text('demo-package'), findsWidgets);
    expect(find.text('MIT'), findsOneWidget);
    expect(find.text('MIT License'), findsOneWidget);
    expect(find.text('Permission is hereby granted'), findsOneWidget);
  });
}
